// Юридические документы сайта (по указанию пользователя - по
// законодательству РФ): пользовательское соглашение, согласие на обработку
// персональных данных (с 1 сентября 2025 года - отдельным документом, 152-ФЗ
// ст. 9), согласие на рекламные рассылки (38-ФЗ ст. 18, необязательное).
// При регистрации галочки соглашения и согласия на обработку обязательны;
// у пользователя сохраняется, какие документы (версия) и когда приняты, с
// какого IP. Новая редакция документов - новая LEGAL_VERSION.
const LEGAL_VERSION = '2026-10-05';

// Проверка галочек регистрации. Возвращает текст ошибки или запись о
// согласиях для пользователя.
function consentsFromRequest(req) {
  const c = req.body && req.body.consents || {};
  if (c.terms !== true) return { error: 'Чтобы зарегистрироваться, примите Пользовательское соглашение.' };
  if (c.pd !== true) return { error: 'Чтобы зарегистрироваться, дайте согласие на обработку персональных данных.' };
  const at = new Date().toISOString();
  return {
    consents: {
      version: LEGAL_VERSION, at, ip: req.ip,
      terms: true, pd: true, marketing: c.marketing === true,
    },
  };
}

module.exports = { LEGAL_VERSION, consentsFromRequest };
